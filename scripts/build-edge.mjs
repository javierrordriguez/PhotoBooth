// Generate the single-file variant required by the Supabase dashboard editor.
// CLI deployments use the modular sources directly.
import fs from "node:fs/promises";
import { URL } from "node:url";
import ts from "typescript";
const root = new URL("../supabase/functions/", import.meta.url);
for (const target of ["device-api", "guest-gallery"]) {
  const files =
    target === "device-api"
      ? [
          "_shared/protocol.ts",
          "_shared/jpeg.ts",
          "_shared/handler.ts",
          "device-api/index.ts",
        ]
      : ["_shared/protocol.ts", "_shared/guest.ts", "guest-gallery/index.ts"];
  const chunks = [];
  for (const file of files) {
    let source = await fs.readFile(new URL(file, root), "utf8");
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
    const imports = ast.statements.filter(ts.isImportDeclaration);
    for (const item of imports.reverse())
      source = source.slice(0, item.pos) + source.slice(item.end);
    chunks.push(source);
  }
  const output =
    "// GENERATED by scripts/build-edge.mjs; edit modular sources instead.\n" +
    'import { createClient } from "npm:@supabase/supabase-js@2.117.3";\n' +
    (target === "device-api" ? 'import jpeg from "npm:jpeg-js@0.4.4";\n' : "") +
    chunks.join("\n");
  await fs.mkdir(new URL("../supabase/dashboard/", import.meta.url), {
    recursive: true,
  });
  await fs.writeFile(
    new URL(`../supabase/dashboard/${target}.ts`, import.meta.url),
    output,
  );
}
